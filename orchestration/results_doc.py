"""Write docs/RESULTS.md from the real pipeline outputs. ``python -m orchestration.results_doc``"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

from common.paths import REPO_ROOT, data_dir, tableau_dir


def _fmt(df: pd.DataFrame) -> str:
    return df.to_markdown(index=False) if hasattr(df, "to_markdown") else df.to_string(index=False)


def table(df: pd.DataFrame, fmts: dict[str, str]) -> str:
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        cells = []
        for c in cols:
            v = r[c]
            cells.append("" if pd.isna(v) else (fmts[c].format(v) if c in fmts else str(v)))
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


def main() -> None:
    meta = json.loads((data_dir() / "model" / "metadata.json").read_text())
    man = json.loads((data_dir() / "prepared" / "ingest_manifest.json").read_text())
    m = pd.read_csv(tableau_dir() / "monthly_summary.csv")
    res = pd.read_csv(tableau_dir() / "monitoring_results.csv")
    obs = m[m["auc"].notna()]
    rag = m["overall_rag"].value_counts().to_dict()
    mm = meta["metrics"]
    csi = res[res.metric == "csi"]
    csi_red = csi[csi.rag == "RED"].groupby("segment").size().sort_values(ascending=False)
    first_red_psi = res[(res.metric == "psi_score") & (res.rag != "GREEN")].sort_values("month")
    by_rag = res.groupby(["metric", "rag"]).size().unstack(fill_value=0)
    for c in ("GREEN", "AMBER", "RED"):
        if c not in by_rag:
            by_rag[c] = 0
    by_rag = by_rag[["GREEN", "AMBER", "RED"]].reset_index()
    sel = m[
        [
            "month",
            "volume",
            "mean_pd",
            "default_rate",
            "psi_score",
            "csi_max",
            "gini",
            "ks",
            "calibration_ratio",
            "hl_pvalue",
            "overall_rag",
        ]
    ]
    fm = {
        "volume": "{:,.0f}",
        "mean_pd": "{:.3f}",
        "default_rate": "{:.3f}",
        "psi_score": "{:.3f}",
        "csi_max": "{:.3f}",
        "gini": "{:.3f}",
        "ks": "{:.3f}",
        "calibration_ratio": "{:.2f}",
        "hl_pvalue": "{:.4f}",
    }
    text = f"""# Results (real run of `make e2e`)

Every number below is generated by `python -m orchestration.results_doc` from the files produced by
one full pipeline run on LendingClub data. Nothing is hand-typed.

## Data
* Source: {man["dataset"]}, licence {man["licence"]}.
* Raw rows scanned: **{man["raw_rows_scanned"]:,}**; prepared (36-month loans issued 2012-01..2016-12):
  **{man["prepared_rows"]:,}** ({man["rows_by_window"]["dev"]:,} development, {man["rows_by_window"]["monitor"]:,} monitoring).
* Resolved outcomes (Fully Paid / Charged Off / Default): {man["resolved_rows"]:,}.
  Default rate: development {man["default_rate_dev"]:.1%}; observable monitoring vintages {man["default_rate_observable_monitor"]:.1%}.

## PD model ({meta["model_version"]}: WoE logistic scorecard, {len(meta["features"])} features)
Train 2012-01..2013-06, out-of-time (OOT) validation 2013-07..2013-12.

| sample | n | AUC | Gini | KS |
|---|---|---|---|---|
| train | {mm["train"]["n"]:,} | {mm["train"]["auc"]:.3f} | {mm["train"]["gini"]:.3f} | {mm["train"]["ks"]:.3f} |
| out-of-time | {mm["out_of_time"]["n"]:,} | {mm["out_of_time"]["auc"]:.3f} | {mm["out_of_time"]["gini"]:.3f} | {mm["out_of_time"]["ks"]:.3f} |
| GBM challenger, OOT | {mm["challenger_out_of_time"]["n"]:,} | {mm["challenger_out_of_time"]["auc"]:.3f} | {mm["challenger_out_of_time"]["gini"]:.3f} | {mm["challenger_out_of_time"]["ks"]:.3f} |

## Monitoring over 36 monthly vintages (2014-01 .. 2016-12)
* Vintages monitored: **{len(m)}**; with observable outcomes (Gini/KS/calibration): **{len(obs)}** (2014-01..2015-12);
  2016 vintages are monitored on population stability only.
* Metrics computed per month: {res.metric.nunique()} metric families, **{len(res):,} metric rows** in total.
* Overall RAG across 36 months: {", ".join(f"{k} {v}" for k, v in rag.items())}.
* Gini on observable vintages: min {obs.gini.min():.3f}, median {obs.gini.median():.3f}, max {obs.gini.max():.3f}
  (development OOT {mm["out_of_time"]["gini"]:.3f}); KS median {obs.ks.median():.3f}.
* Calibration ratio (observed / predicted default rate): min {obs.calibration_ratio.min():.2f}, max {obs.calibration_ratio.max():.2f}.
* Score PSI vs development: max {m.psi_score.max():.3f} (first non-green month: {first_red_psi.month.iloc[0] if len(first_red_psi) else "none"}).
* Largest characteristic drift (CSI) breaches by feature (RED months): {", ".join(f"{k} {v}" for k, v in csi_red.head(5).items()) or "none"}.

### RAG counts by metric (month x segment rows)
{table(by_rag, {})}

### Monthly summary
{table(sel, fm)}

## Reading these results honestly
* The model is deliberately simple (a 7-feature scorecard, OOT Gini ~{mm["out_of_time"]["gini"]:.2f}); LendingClub
  applicants are pre-screened, so discrimination is modest and typical of public consumer-loan data.
* Calibration tests with ~10k loans a month have very high power: even small mis-calibration gives a
  small Hosmer-Lemeshow p-value, so the overall status is frequently AMBER/RED. This is a finding about
  test sensitivity at large n, discussed in `docs/WALKTHROUGH.md`.
* This is public consumer-loan data, not bank corporate data; no company credit-rating model was built.
"""
    Path(REPO_ROOT / "docs" / "RESULTS.md").write_text(text)
    print("wrote docs/RESULTS.md")


if __name__ == "__main__":
    main()
